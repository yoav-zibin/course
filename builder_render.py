"""Render untrusted game HTML only inside a network-isolated browser iframe."""
import json
import os
from pathlib import Path
import shutil
import subprocess

ARTIFACT_ROOT = Path(os.environ.get('BUILDER_ARTIFACT_DIR', str(Path(__file__).parent / '.builder-artifacts')))


def _node_binary():
    """Find Node.js even when the service's PATH does not include it.

    The production service runs under a minimal systemd PATH, so a Node
    installed via nvm/Volta or into /usr/local is invisible to a bare
    'node' lookup and every build died at the screenshot stage with a
    raw '[Errno 2] No such file or directory'. Look in the usual places
    before giving up."""
    found = shutil.which('node')
    if found:
        return found
    candidates = ['/usr/local/bin/node', '/usr/bin/node', '/opt/node/bin/node',
                  '/snap/bin/node', '/opt/homebrew/bin/node']
    home = Path.home()
    nvm = home / '.nvm' / 'versions' / 'node'
    if nvm.is_dir():
        candidates += [str(p) for p in sorted(nvm.glob('*/bin/node'), reverse=True)]
    candidates.append(str(home / '.volta' / 'bin' / 'node'))
    for candidate in candidates:
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    return None


def _failure_detail(stderr):
    """The meaningful tail of the render script's stderr.

    Host-level agents (the Datadog tracer on the production VM) banner
    every Node process's stderr with a large configuration dump; without
    filtering, that banner is what surfaces as the failure. Drop banner
    lines and keep the script's own error lines."""
    lines = [line for line in (stderr or '').splitlines() if 'datadog' not in line.lower()]
    return '\n'.join(lines).strip()[-2000:]


def preflight_browser():
    """Whether the screenshot stage could run at all on this host.

    render_game only discovers a missing Node.js or Playwright module
    after the build has spent model calls writing the client, so the
    build checks both up front. This resolves the 'playwright' module
    exactly the way the render script will — Node walks up from the
    script's own directory — and never launches a browser. Returns
    (ok, detail) with a plain-language detail when it cannot run."""
    node = _node_binary()
    if node is None:
        return False, ('Node.js was not found on the server (searched PATH, '
                       '/usr/local/bin, /usr/bin, nvm and Volta installs)')
    scripts = str(Path(__file__).parent / 'scripts')
    try:
        process = subprocess.run(
            [node, '-e', "require.resolve('playwright', {paths: [process.argv[1]]})", scripts],
            text=True, capture_output=True, timeout=15)
    except (OSError, subprocess.SubprocessError) as exc:
        return False, f'Node.js could not be run to check for Playwright: {exc}'
    if process.returncode:
        detail = _failure_detail(process.stderr)
        return False, ("the 'playwright' Node module is not installed where the "
                       'render script can find it' + (f': {detail}' if detail else ''))
    return True, ''


def render_game(draft_id, job_id, code, cases, timeout=300, tutorial=None):
    # UUID job names are generated by the server, never used directly from input.
    destination = ARTIFACT_ROOT / job_id
    destination.mkdir(parents=True, exist_ok=True)
    node = _node_binary()
    if node is None:
        raise RuntimeError('Browser verification unavailable: Node.js was not found on the server '
                           '(searched PATH, /usr/local/bin, /usr/bin, nvm and Volta installs). '
                           'The server needs Node.js with Playwright to render game screenshots.')
    process = subprocess.run([node, str(Path(__file__).parent/'scripts/builder-render.cjs')],
        input=json.dumps({'code':code,'cases':cases,'tutorial':tutorial,'destination':str(destination)}),
        text=True,capture_output=True,timeout=min(300,timeout))
    if process.returncode:
        raise RuntimeError('Browser verification unavailable or failed: '+_failure_detail(process.stderr))
    return json.loads(process.stdout)
